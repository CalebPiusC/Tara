"""Word (.docx) renderer using python-docx (MIT)."""
from __future__ import annotations

import io
from typing import Any

from .model import Block, DocStyle, Document, inline_runs


def _set_font(run_or_style: Any, name: str, size: float | None = None, bold: bool | None = None,
              rgb: tuple[int, int, int] | None = None) -> None:
    from docx.oxml.ns import qn
    from docx.shared import Pt, RGBColor
    f = run_or_style.font
    f.name = name
    rpr = run_or_style.element.get_or_add_rPr() if hasattr(run_or_style.element, "get_or_add_rPr") else run_or_style.element.rPr
    if rpr is not None:
        fonts = rpr.rFonts if rpr.rFonts is not None else rpr._add_rFonts()
        for attr in ("w:ascii", "w:hAnsi", "w:eastAsia", "w:cs"):
            fonts.set(qn(attr), name)
    if size is not None:
        f.size = Pt(size)
    if bold is not None:
        f.bold = bold
    if rgb is not None:
        f.color.rgb = RGBColor(*rgb)


def _add_runs(paragraph: Any, text: str, style: DocStyle, *, mono: bool = False) -> None:
    for chunk, bold, italic in inline_runs(text):
        run = paragraph.add_run(chunk)
        if bold:
            run.bold = True
        if italic:
            run.italic = True
        if mono:
            _set_font(run, style.font_mono, style.size_body - 1)


def _page_number_field(paragraph: Any) -> None:
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    run = paragraph.add_run()
    for kind, text in (("begin", None), (None, "PAGE"), ("end", None)):
        if kind:
            el = OxmlElement("w:fldChar")
            el.set(qn("w:fldCharType"), kind)
        else:
            el = OxmlElement("w:instrText")
            el.set(qn("xml:space"), "preserve")
            el.text = text
        run._r.append(el)


def render_docx(doc: Document, style: DocStyle | None = None) -> bytes:
    from docx import Document as WordDocument
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.shared import Cm, Pt

    style = style or DocStyle()
    word = WordDocument()
    sec = word.sections[0]
    if style.page == "A4":
        sec.page_width, sec.page_height = Cm(21.0), Cm(29.7)
    else:
        sec.page_width, sec.page_height = Cm(21.59), Cm(27.94)
    for side in ("left_margin", "right_margin", "top_margin", "bottom_margin"):
        setattr(sec, side, Cm(style.margin_cm))

    normal = word.styles["Normal"]
    _set_font(normal, style.font_body, style.size_body)
    normal.paragraph_format.space_after = Pt(6)
    for name, size in (("Heading 1", style.size_h1), ("Heading 2", style.size_h2), ("Heading 3", style.size_h3)):
        _set_font(word.styles[name], style.font_heading, size, True, style.accent_rgb)
    _set_font(word.styles["Title"], style.font_heading, style.size_h1 + 6, True, style.accent_rgb)

    props = word.core_properties
    props.title, props.author = doc.title[:250], doc.author[:250]
    props.comments = "Generated by Tara. Review before relying on it."
    word.add_paragraph(doc.title, style="Title")
    if doc.subtitle:
        p = word.add_paragraph()
        run = p.add_run(doc.subtitle)
        run.italic = True
    if doc.created:
        p = word.add_paragraph()
        r = p.add_run(f"Created: {doc.created}")
        r.font.size = Pt(style.size_body - 2)
    if doc.confidential:
        p = word.add_paragraph()
        r = p.add_run("CONFIDENTIAL")
        r.bold = True

    for b in doc.blocks:
        _render_block(word, b, style)

    footer = sec.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    if doc.footer:
        footer.add_run(doc.footer + "   |   Page ")
    else:
        footer.add_run("Page ")
    _page_number_field(footer)
    buf = io.BytesIO()
    word.save(buf)
    return buf.getvalue()


def _render_block(word: Any, b: Block, style: DocStyle) -> None:
    from docx.shared import Pt
    if b.kind == "heading":
        word.add_heading(b.text, level=b.level)
    elif b.kind == "paragraph":
        _add_runs(word.add_paragraph(), b.text, style)
    elif b.kind == "bullets":
        for item in b.items:
            _add_runs(word.add_paragraph(style="List Bullet"), item, style)
    elif b.kind == "numbered":
        for item in b.items:
            _add_runs(word.add_paragraph(style="List Number"), item, style)
    elif b.kind == "code":
        p = word.add_paragraph()
        r = p.add_run(b.text)
        _set_font(r, style.font_mono, style.size_body - 1)
    elif b.kind == "rule":
        word.add_paragraph("_" * 40)
    elif b.kind == "table":
        table = word.add_table(rows=1, cols=len(b.headers))
        table.style = "Table Grid"
        for i, h in enumerate(b.headers):
            cell = table.rows[0].cells[i]
            cell.text = ""
            run = cell.paragraphs[0].add_run(h)
            run.bold = True
            run.font.size = Pt(style.size_body - 1)
        for row in b.rows:
            cells = table.add_row().cells
            for i, text in enumerate(row):
                cells[i].text = ""
                _add_runs(cells[i].paragraphs[0], text, style)
        word.add_paragraph()
