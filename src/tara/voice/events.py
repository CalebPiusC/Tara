"""Provider-neutral voice session contracts. The application depends on these,
not on Google SDK types (docs/GEMINI_LIVE.md).

Response ids are generated by OUR adapter (a counter bumped when new model audio
starts after a turn ended or was interrupted). Google's Live messages carry no
response id, so ids exist only to reject stale audio inside this process.
"""
from __future__ import annotations

from collections.abc import AsyncIterator
from dataclasses import dataclass, field
from typing import Any, Protocol


@dataclass(frozen=True)
class VoiceEvent:
    pass


@dataclass(frozen=True)
class SessionReady(VoiceEvent):
    connect_ms: float = 0.0


@dataclass(frozen=True)
class ResumptionHandle(VoiceEvent):
    handle: str
    resumable: bool = True


@dataclass(frozen=True)
class ResponseAudio(VoiceEvent):
    response_id: int
    pcm: bytes
    sample_rate: int = 24000


@dataclass(frozen=True)
class InputTranscript(VoiceEvent):
    text: str
    finished: bool = False


@dataclass(frozen=True)
class OutputTranscript(VoiceEvent):
    text: str
    response_id: int = 0
    finished: bool = False


@dataclass(frozen=True)
class GenerationComplete(VoiceEvent):
    response_id: int


@dataclass(frozen=True)
class TurnComplete(VoiceEvent):
    response_id: int
    reason: str = ""


@dataclass(frozen=True)
class Interrupted(VoiceEvent):
    response_id: int


@dataclass(frozen=True)
class ToolRequest:
    call_id: str
    name: str
    args: dict[str, Any]


@dataclass(frozen=True)
class ToolCallRequested(VoiceEvent):
    calls: tuple[ToolRequest, ...]


@dataclass(frozen=True)
class ToolCallsCancelled(VoiceEvent):
    call_ids: tuple[str, ...]


@dataclass(frozen=True)
class GoAway(VoiceEvent):
    time_left_s: float | None = None


@dataclass(frozen=True)
class Disconnected(VoiceEvent):
    reason: str                 # redacted, short
    recoverable: bool = True    # False for auth/config errors: do not retry


@dataclass(frozen=True)
class ToolDecl:
    name: str
    description: str
    parameters: dict[str, Any]   # JSON-schema-like object {type: OBJECT, properties, required}


@dataclass(frozen=True)
class VoiceSessionConfig:
    system_instruction: str
    voice_name: str = ""
    tools: tuple[ToolDecl, ...] = ()
    input_transcription: bool = True
    output_transcription: bool = True
    resumption: bool = True
    context_compression: bool = True       # docs: audio-only sessions are capped at 15 min without it
    activity_handling: str = "interrupts"  # "interrupts" | "none"
    silence_duration_ms: int | None = None
    proactive_audio: bool = False
    tool_behavior: str = "default"         # default | blocking | non_blocking
    extra: dict[str, Any] = field(default_factory=dict)


class VoiceSession(Protocol):
    async def send_audio(self, pcm16_16k: bytes) -> None: ...
    async def end_audio_stream(self) -> None: ...
    async def send_text(self, text: str) -> None: ...
    async def send_context(self, text: str) -> None: ...
    async def send_tool_result(self, call_id: str, name: str, result: dict[str, Any]) -> None: ...
    def events(self) -> AsyncIterator[VoiceEvent]: ...
    async def close(self) -> None: ...


class VoiceProvider(Protocol):
    async def open(self, config: VoiceSessionConfig, resume_handle: str | None = None) -> VoiceSession: ...
