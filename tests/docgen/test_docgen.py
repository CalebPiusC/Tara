def test_job_board_lifecycle_isolation_and_limits():
    async def go():
        board = JobBoard(max_running=1, timeout_s=1.0)
        gate = asyncio.Event()

        async def work():
            await gate.wait()
            return {"file": "a.docx"}
        j = board.start("s1", "document", work)
        await asyncio.sleep(0)
        assert board.get("s1", j.job_id).state == "running" and board.get("other", j.job_id) is None
        with pytest.raises(JobLimitReached):
            board.start("s1", "document", work)                             # bounded: one running job
        gate.set()
        await j.task
        assert board.get("s1", j.job_id).public() == {"job_id": j.job_id, "kind": "document", "state": "completed", "result": {"file": "a.docx"}}
        await board.close()
    run(go())


def test_job_failures_timeouts_and_cancellation_are_honest():
    async def go():
        board = JobBoard(max_running=3, timeout_s=0.1)

        async def boom():
            raise ValueError("secret detail")

        async def slow():
            await asyncio.sleep(5)
        failed, slow_job = board.start("s", "k", boom), board.start("s", "k", slow)
        await asyncio.gather(failed.task, slow_job.task)
        assert failed.state == "failed" and failed.error == "ValueError" and "secret" not in str(failed.public())
        assert slow_job.state == "failed" and slow_job.error == "timed out"
        board2 = JobBoard(timeout_s=5)
        j = board2.start("s", "k", slow)
        await asyncio.sleep(0)
        assert board2.cancel("s", j.job_id) and not board2.cancel("other", j.job_id)
        await asyncio.gather(j.task, return_exceptions=True)
        assert j.state == "cancelled" and "result" not in j.public()
        await board2.close()
    run(go())


def test_job_board_prunes_old_results():
    async def go():
        t = [0.0]
        board = JobBoard(ttl_s=10, max_kept=2, clock=lambda: t[0])

        async def quick():
            return 1
        ids = []
        for _ in range(3):
            j = board.start("s", "k", quick)
            await j.task
            ids.append(j.job_id)
            t[0] += 1
        board.start("s", "k", quick)
        assert board.get("s", ids[0]) is None and len(board.list("s")) <= 3
        t[0] += 100
        await (board.start("s", "k", quick)).task
        assert all(board.get("s", i) is None for i in ids)
    run(go())
